"""Generates mpc_povar_define.abap (entity PoVar / PoVarSet) from zpovar_s_row.ddls.txt. Run: python3 gen_povar.py"""
import os, re
P = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(P, 'zpovar_s_row.ddls.txt')).read()
fields = re.findall(r'^\s+(\w+)\s*:\s*([\w.(),]+);', src, re.M)
def camel(n): return ''.join(p.capitalize() for p in n.split('_'))
FILTER = {'werks', 'matnr', 'aufnr', 'post_type', 'date_from', 'date_to', 'date_type', 'grain'}
LEN = {'matnr': 18, 'parent': 18, 'maktx': 40, 'mtart': 4, 'matkl': 9, 'werks': 4, 'charg': 10, 'aufnr': 12, 'mblnr': 10, 'mjahr': 4, 'bwtar': 10}
L = ["  METHOD povar_define.",
     "    \" Variance check (ZMM_PCOST / ZMM_COST): PoVarSet, rows of ZPOVAR_S_ROW (ZCL_MM_PO_VARIANCE). Generated by sap/povar/gen_povar.py.",
     "    DATA: lo_et TYPE REF TO /iwbep/if_mgw_odata_entity_typ,",
     "          lo_es TYPE REF TO /iwbep/if_mgw_odata_entity_set,",
     "          lo_p  TYPE REF TO /iwbep/if_mgw_odata_property.",
     "    lo_et = model->create_entity_type( iv_entity_type_name = 'PoVar' iv_def_entity_set = abap_false )."]
for n, t in fields:
    L.append(f"    lo_p = lo_et->create_property( iv_property_name = '{camel(n)}' iv_abap_fieldname = '{n.upper()}' ).")
    if n == 'rowid': L.append("    lo_p->set_is_key( ).")
    if t.startswith('abap.int4'): L.append("    lo_p->set_type_edm_int32( ).")
    elif t == 'dats': L += ["    lo_p->set_type_edm_datetime( ).", "    lo_p->set_precison( iv_precision = 7 ).", "    lo_p->set_nullable( abap_true )."]
    elif t.startswith('abap.dec'):
        a, b = re.findall(r'\d+', t)
        L += ["    lo_p->set_type_edm_decimal( ).", f"    lo_p->set_precison( iv_precision = {b} ).", f"    lo_p->set_maxlength( iv_max_length = {a} )."]
    else:
        m = re.search(r'char\((\d+)\)', t)
        L += ["    lo_p->set_type_edm_string( ).", f"    lo_p->set_maxlength( iv_max_length = {int(m.group(1)) if m else LEN[n]} )."]
        if n in ('matnr', 'parent'): L.append("    lo_p->set_conversion_exit( 'MATN1' ).")
    L += ["    lo_p->set_creatable( abap_false ).", "    lo_p->set_updatable( abap_false ).", "    lo_p->set_sortable( abap_false )."]
    if t != 'dats': L.append("    lo_p->set_nullable( abap_false ).")
    L.append(f"    lo_p->set_filterable( {'abap_true' if n in FILTER else 'abap_false'} ).")
L += ["    lo_et->bind_structure( iv_structure_name = 'ZPOVAR_S_ROW' iv_bind_conversions = 'X' ).",
      "    lo_es = lo_et->create_entity_set( 'PoVarSet' ).",
      "    lo_es->set_creatable( abap_false ).", "    lo_es->set_updatable( abap_false ).", "    lo_es->set_deletable( abap_false ).",
      "    lo_es->set_pageable( abap_false ).", "    lo_es->set_addressable( abap_true ).", "    lo_es->set_has_ftxt_search( abap_false ).", "  ENDMETHOD."]
open(os.path.join(P, 'mpc_povar_define.abap'), 'w').write('\n'.join(L) + '\n')
print(len(fields), 'fields')
